"""Parses scripts/content/programmes_in_action.md (the client's "Programmes in
Action" document) into src/content/usecases.ts. The wording is kept as written;
only dashes are normalised (the site uses none) and the old service name
"GTM AI Twin" becomes "Lead Gen AI Twin".
Usage: python3 scripts/content/parse_usecases.py
"""
import json, re, sys, os
sys.path.insert(0, os.path.dirname(__file__))
from textfix import undash

SRC = os.path.join(os.path.dirname(__file__), "programmes_in_action.md")
OUT = os.path.join(os.path.dirname(__file__), "..", "..", "src", "content", "usecases.data.ts")

def clean(s):
    s = s.replace("GTM AI Twin", "Lead Gen AI Twin")
    return undash(s).strip()

def strip_md(s):
    return re.sub(r"\*\*(.*?)\*\*", r"\1", s)

STOP = {"a", "an", "the", "and", "for", "of", "to", "on", "in", "its", "it", "into", "with", "from", "before", "by", "as", "that", "what", "who", "so"}

def slugify(s, limit=60):
    words = [w for w in re.sub(r"[^a-z0-9]+", " ", s.lower()).split() if w not in STOP]
    out = ""
    for w in words:
        if len(out) + len(w) + 1 > limit: break
        out = (out + "-" + w).strip("-")
    return out

text = open(SRC, encoding="utf-8").read()
body = text[text.index("\n---\n"):]
families = re.split(r"\n## \d+ · ", body)[1:]
cases, problems = [], []
for fam_block in families:
    fam_name = fam_block.split("\n", 1)[0].strip()
    for block in re.split(r"\n### ", fam_block)[1:]:
        title = block.split("\n", 1)[0].strip()
        meta = re.search(r"\*\*Service:\*\* (.+?) · \*\*Industry:\*\* (.+?) · \*\*Family:\*\* (.+)", block)
        hook = re.search(r"\n\*([^*\n].+?)\*\n", block)
        def bullet(label):
            m = re.search(r"- \*\*" + label + r":\*\* (.+)", block)
            return clean(m.group(1)) if m else None
        glance = dict(re.findall(r"\n\| ([^|\n]+?) \| ([^|\n]+?) \|", block))
        glance.pop("At a glance", None); glance.pop("---", None)
        def section(n):
            m = re.search(r"#### 0" + str(n) + r" · [^\n]+\n(.*?)(?=\n#### |\n\*\*Related services|\Z)", block, re.S)
            return m.group(1).strip() if m else ""
        def bullets(t):
            out = []
            for line in t.splitlines():
                line = line.strip()
                if not line.startswith("- "): continue
                m = re.match(r"- \*\*(.+?)\*\*[.:]?\s*(.*)", line)
                out.append({"t": clean(m.group(1)).rstrip(".:"), "b": clean(m.group(2))} if m else {"t": "", "b": clean(line[2:])})
            return out
        def paras(t):
            return [clean(strip_md(p)) for p in re.split(r"\n\s*\n", t) if p.strip() and not p.strip().startswith("- ")]
        outcome = section(5)
        related = re.search(r"\*\*Related services:\*\* (.+)", block)
        cta = re.search(r"\n\*\*(.+?)\*\* → (.+)", block)
        note = re.search(r"\n\*(Client profile is [^*]+)\*", block)
        if not (meta and hook and bullet("The challenge")): problems.append(title)
        service, industry, family = (clean(x) for x in meta.groups()) if meta else ("", "", fam_name)
        cases.append({
            "slug": slugify(title),
            "title": clean(title),
            "service": service, "industry": industry, "family": family,
            "hook": clean(hook.group(1)) if hook else "",
            "challenge": bullet("The challenge"), "approach": bullet("Our approach"), "result": bullet("The result"),
            "glance": {clean(k): clean(v) for k, v in glance.items()},
            "situation": paras(section(1)),
            "question": " ".join(paras(section(2))),
            "whatWeDid": bullets(section(3)),
            "evidence": [b["b"] if not b["t"] else (b["t"] + (": " + b["b"] if b["b"] else "")) for b in bullets(section(4))],
            "outcome": bullets(outcome),
            "outcomeNote": " ".join(paras(outcome)),
            "whatChanged": paras(section(6)),
            "related": [clean(x) for x in related.group(1).split(" · ")] if related else [],
            "ctaHook": clean(cta.group(1)) if cta else "",
            "note": clean(note.group(1)) if note else "",
        })
slugs = [c["slug"] for c in cases]
assert len(slugs) == len(set(slugs)), "duplicate slugs"
print(f"{len(cases)} use cases, {len(problems)} incomplete: {problems}")
if "--write" in sys.argv:
    ts = (
        "// Generated by scripts/content/parse_usecases.py from the client's\n"
        "// \"Programmes in Action\" document. Edit the document, then re-run the script.\n"
        "export type UseCase = {\n"
        "  slug: string; title: string; service: string; industry: string; family: string;\n"
        "  hook: string; challenge: string; approach: string; result: string;\n"
        "  glance: Record<string, string>;\n"
        "  situation: string[]; question: string;\n"
        "  whatWeDid: { t: string; b: string }[]; evidence: string[];\n"
        "  outcome: { t: string; b: string }[]; outcomeNote: string;\n"
        "  whatChanged: string[]; related: string[]; ctaHook: string; note: string;\n"
        "};\n\n"
        f"export const useCases: UseCase[] = {json.dumps(cases, indent=1, ensure_ascii=False)};\n"
    )
    open(OUT, "w", encoding="utf-8").write(ts)
    print("wrote", OUT)
